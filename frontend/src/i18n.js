const DICTS = {
  en,
  "zh-Hant": zhHant,
  "zh-Hans": zhHans,
  pa,
  fa,
  "pt-PT": ptPT,
};

export function isRTL(lang) {
  return lang === "fa";
}

export function normalizeLang(v) {
  if (!v) return "en";
  const s = String(v).toLowerCase();
  if (s.startsWith("zh-hant") || s === "zh-tw" || s === "zh-hk") return "zh-Hant";
  if (s.startsWith("zh")) return "zh-Hans";
  if (s.startsWith("pa")) return "pa";
  if (s.startsWith("fa")) return "fa";
  if (s.startsWith("pt")) return "pt-PT";
  if (s.startsWith("fr")) return "fr";
  return "en";
}

export function useT(lang) {
  const dict = DICTS[normalizeLang(lang)] || en;
  const t = (key) => dict[key] || en[key] || key;
  return t;
}

// Suffix used to preserve ?lang= across internal navigation
export function langQS(lang) {
  const n = normalizeLang(lang);
  return n === "en" ? "" : `?lang=${encodeURIComponent(n)}`;
}
